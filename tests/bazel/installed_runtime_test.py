class InstalledRuntimeTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.source = ARGS.source.absolute().parent.parent
        cls.wheels = [p.absolute() for p in ARGS.dependency_wheel]
        import sonic_py_common
        import sonic_platform_base
        import portconfig
        import sonic_yang
        roots = [cls.source,
                 Path(sonic_py_common.__file__).absolute().parent.parent,
                 Path(sonic_platform_base.__file__).absolute().parent.parent,
                 Path(portconfig.__file__).absolute().parent,
                 Path(sonic_yang.__file__).absolute().parent]
        cls.installed = cls.enterClassContext(installed_wheels(cls.wheels, exclude_source_roots=roots))
        # psud's import-time hardware provider is the same explicit fixture
        # used by its original suite. Borrow only sonic_platform, retaining
        # the real declared Common binding rather than mocked_libs/swsscommon.
        cls.hardware_fixture = cls.installed.root / "hardware-fixture"
        shutil.copytree(cls.source / "sonic-psud/tests/mocked_libs/sonic_platform",
                        cls.hardware_fixture / "sonic_platform")
        cls.payloads = []
        for archive in ARGS.runtime:
            files = {}
            with tarfile.open(archive, "r:") as stream:
                for member in stream:
                    path = Path(member.name)
                    assert not path.is_absolute() and ".." not in path.parts
                    assert member.uid == member.gid == 0
                    if member.isdir():
                        assert member.mode == 0o755
                        continue
                    assert member.isfile()
                    assert member.mode == (0o755 if path.is_relative_to("usr/local/bin") else 0o644)
                    data = stream.extractfile(member).read()
                    files[str(path)] = data
                    if path.is_relative_to("usr/local/bin"):
                        target = cls.installed.scripts / path.name
                    else:
                        target = cls.installed.site / path.relative_to("usr/local/lib/python3.13/dist-packages")
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_bytes(data)
                    target.chmod(member.mode)
            cls.payloads.append(files)

    def test_original_payload_metadata_and_record(self):
        metadata = {json.loads(p.read_text())["distribution"]: (p, json.loads(p.read_text())) for p in ARGS.metadata}
        wheels = {path.name: path for path in ARGS.owner_wheel}
        observed = []
        site = "usr/local/lib/python3.13/dist-packages"
        for files in self.payloads:
            headers = [p for p in files if p.endswith(".dist-info/METADATA")]
            self.assertEqual(len(headers), 1)
            header = headers[0]
            message = BytesParser().parsebytes(files[header])
            name = message["Name"]
            setup = self.source / name / "setup.py"
            contract = setup_contract(setup)
            prefix = header.rsplit("/", 1)[0]
            expected = {site + "/" + p: source.read_bytes() for p, source in expected_sources(contract, setup.parent).items()}
            # These two files are generated by the original setup GrpcTool,
            # not present in the source checkout's find_packages enumeration.
            if name == "sonic-ycabled":
                generated = {site + "/proto_out/" + p for p in ("linkmgr_grpc_driver_pb2.py", "linkmgr_grpc_driver_pb2_grpc.py")}
                self.assertTrue(generated <= files.keys())
            else:
                generated = set()
            for script in contract.get("scripts", []):
                path = "usr/local/bin/" + Path(script).name
                self.assertEqual(files[path].split(b"\n", 1)[1], (setup.parent / script).read_bytes().split(b"\n", 1)[1])
                self.assertEqual(files[path].split(b"\n", 1)[0], b"#!/usr/bin/python3")
                expected[path] = files[path]
            entries = contract.get("entry_points", {}).get("console_scripts", [])
            if entries:
                config = configparser.ConfigParser()
                config.read_string(files[prefix + "/entry_points.txt"].decode())
                expected_entries = dict(tuple(v.strip() for v in entry.split("=", 1)) for entry in entries)
                self.assertEqual(dict(config["console_scripts"]), expected_entries)
                for command in expected_entries:
                    path = "usr/local/bin/" + command
                    self.assertEqual(files[path].split(b"\n", 1)[0], b"#!/usr/bin/python3")
                    expected[path] = files[path]
            self.assertEqual({p for p in files if not p.startswith(prefix + "/")}, set(expected) | generated)
            for path, data in expected.items():
                self.assertEqual(files[path], data, path)
            for header_name, field in {
                "Name": "name", "Version": "version", "Summary": "description", "License": "license",
                "Author": "author", "Author-email": "author_email", "Home-page": "url",
                "Maintainer": "maintainer", "Maintainer-email": "maintainer_email", "Keywords": "keywords",
            }.items():
                self.assertEqual(message[header_name], contract.get(field), (name, field))
            self.assertEqual(set(message.get_all("Classifier", [])), set(contract.get("classifiers", [])))
            requires = set(map(normalized_requirement, contract.get("install_requires", [])))
            for extra, values in contract.get("extras_require", {}).items():
                for value in values:
                    requires.add(normalized_requirement(value + '; extra == "' + extra + '"'))
            self.assertEqual(set(map(normalized_requirement, message.get_all("Requires-Dist", []))), requires)
            path, info = metadata[name]
            self.assertEqual(info["version"], contract["version"])
            self.assertEqual(set(map(normalized_requirement, info["requires_dist"])), requires)
            self.assertEqual(info["requires_python"], contract.get("python_requires", ""))
            wheel = wheels.pop(info["wheel"]["filename"])
            self.assertEqual(info["wheel"]["sha256"], hashlib.sha256(wheel.read_bytes()).hexdigest())
            with zipfile.ZipFile(wheel) as archive:
                wheel_metadata = archive.read(Path(prefix).name + "/METADATA")
            self.assertEqual(files[header], wheel_metadata)
            self.assertEqual(info["wheel"]["metadata_sha256"], hashlib.sha256(wheel_metadata).hexdigest())
            self.assertEqual(info["wheel"]["tags"], ["py3-none-any"])
            record = prefix + "/RECORD"
            rows = list(csv.reader(io.StringIO(files[record].decode())))
            recorded = set()
            for relative, digest, size in rows:
                filename = posixpath.normpath(site + "/" + relative)
                recorded.add(filename)
                if filename == record:
                    self.assertEqual((digest, size), ("", ""))
                else:
                    data = files[filename]
                    algorithm = digest.split("=", 1)[0]
                    expected_digest = algorithm + "=" + base64.urlsafe_b64encode(hashlib.new(algorithm, data).digest()).decode().rstrip("=")
                    self.assertEqual((digest, size), (expected_digest, str(len(data))))
            self.assertEqual(recorded, set(files))
            observed.append({"distribution": name, "files": len(files), "runtime_metadata_sha256": hashlib.sha256(path.read_bytes()).hexdigest()})
        self.assertEqual(set(metadata), {v["distribution"] for v in observed})
        self.assertFalse(wheels)
        DETAILS["distributions"] = observed

